import Forecast
import Foundation

// Forecast data track dev tool.
//   fcdata cities [--geonames dir] [--out Sources/Forecast/Data/CityList.swift]   build the city catalog from GeoNames
//   fcdata generate --out dir                                                       live Open-Meteo → forecast.bin/short.bin (+ WC24 containers)
//   fcdata dump <forecast.bin> [short.bin] [--city name]                            parse with the decomp-faithful parser

let args = Array(CommandLine.arguments.dropFirst())
func opt(_ k: String) -> String? { args.firstIndex(of: k).flatMap { $0 + 1 < args.count ? args[$0 + 1] : nil } }
func fail(_ s: String) -> Never { FileHandle.standardError.write((s + "\n").data(using: .utf8)!); exit(1) }

// MARK: cities

func buildCities() throws {
    let dir = URL(fileURLWithPath: opt("--geonames") ?? (NSHomeDirectory() + "/Library/Caches/ForecastChannel/geonames"))
    let out = opt("--out") ?? "Sources/Forecast/Data/CityList.swift"
    func lines(_ f: String) throws -> [[Substring]] {
        try String(contentsOf: dir.appendingPathComponent(f), encoding: .utf8).split(whereSeparator: \.isNewline)
            .filter { !$0.hasPrefix("#") }.map { $0.split(separator: "\t", omittingEmptySubsequences: false) }
    }
    var admin1: [String: String] = [:]
    for r in try lines("admin1CodesASCII.txt") where r.count > 1 { admin1[String(r[0])] = String(r[1]) }
    var countries: [String: String] = [:]
    for r in try lines("countryInfo.txt") where r.count > 4 { countries[String(r[0])] = String(r[4]) }
    struct Row { let name: String, ascii: String, iso: String, admin: String, lat: Double, lon: Double, pop: Int, fcode: String }
    let rows = try lines("cities15000.txt").compactMap { r -> Row? in
        guard r.count > 14, let lat = Double(r[4]), let lon = Double(r[5]), let pop = Int(r[14]) else { return nil }
        return Row(name: String(r[1]), ascii: String(r[2]), iso: String(r[8]), admin: String(r[10]), lat: lat, lon: lon, pop: pop, fcode: String(r[7]))
    }
    // The channel font (font_weather_city.brfnt) covers Latin-1 at most; fall back to ASCII names otherwise.
    func display(_ r: Row) -> String { r.name.unicodeScalars.allSatisfy { $0.value <= 0xFF } ? r.name : r.ascii }

    // Home (US): top 3 per state (+DC) plus every city ≥150k.
    let us = rows.filter { $0.iso == "US" && admin1["US.\($0.admin)"] != nil }
    var home: [Row] = []
    for (_, g) in Dictionary(grouping: us, by: \.admin) {
        let s = g.sorted { $0.pop > $1.pop }
        home += s.prefix(3) + s.dropFirst(3).filter { $0.pop >= 150_000 }
    }
    // World: national capitals ≥500k plus any city ≥3M (non-US), one entry per name+country.
    var seen = Set<String>()
    let world = rows.filter { $0.iso != "US" && (($0.fcode == "PPLC" && $0.pop >= 500_000) || $0.pop >= 3_000_000) }
        .sorted { $0.pop > $1.pop }
        .filter { seen.insert("\(display($0))|\($0.iso)").inserted }

    func esc(_ s: String) -> String { s.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") }
    var src = """
    // GENERATED by `fcdata cities` — do not edit.
    // City data © GeoNames (https://www.geonames.org), licensed CC-BY 4.0 (cities15000, admin1CodesASCII, countryInfo).
    // \(home.count) home (US) cities, \(world.count) world cities.
    // swiftlint:disable all
    public enum CityList {
        public static let all: [CatalogCity] = home + world
        static let home: [CatalogCity] = [

    """
    for r in home.sorted(by: { (admin1["US.\($0.admin)"]!, -$0.pop) < (admin1["US.\($1.admin)"]!, -$1.pop) }) {
        src += "        .init(\"\(esc(display(r)))\", \"\(esc(admin1["US.\(r.admin)"]!))\", \"United States\", \"US\", \(r.lat), \(r.lon), \(r.pop), true),\n"
    }
    src += "    ]\n    static let world: [CatalogCity] = [\n"
    for r in world {
        src += "        .init(\"\(esc(display(r)))\", nil, \"\(esc(countries[r.iso] ?? r.iso))\", \"\(r.iso)\", \(r.lat), \(r.lon), \(r.pop), false),\n"
    }
    src += "    ]\n}\n"
    try src.write(toFile: out, atomically: true, encoding: .utf8)
    print("wrote \(out): \(home.count) home, \(world.count) world")
}

// MARK: dump

func dayLine(_ d: DayForecast, _ f: ForecastFile) -> String {
    let name = f.weatherName(for: d.weather) ?? String(format: "?%04X", d.weather)
    return "\(name) (disp \(String(format: "%04X", f.displayCode(for: d.weather)))) hi \(d.highF)°F/\(d.highC)°C (\(d.highFDiff >= 0 ? "+" : "")\(d.highFDiff)) "
        + "lo \(d.lowF)°F/\(d.lowC)°C  precip \(d.precipitation)  wind dir \(d.windDirection) \(d.windMph)mph  UV \(d.uvIndex)  slots \(d.slots.map { String(format: "%04X", $0) })"
}

func dump(_ fPath: String, _ sPath: String?) throws {
    let fb = try WC24Container.unwrap([UInt8](Data(contentsOf: URL(fileURLWithPath: fPath))))
    let sb = try sPath.map { try WC24Container.unwrap([UInt8](Data(contentsOf: URL(fileURLWithPath: $0)))) }
    if let sb {
        let v = ForecastValidator.validate(forecast: fb, short: sb, now: WC24Time.minutes(Date()), language: 1, regionType: 1)
        print("fn_8000C734 validation: \(v)")
    }
    let f = try ForecastFile(fb)
    let h = f.header
    print("forecast.bin \(fb.count) bytes  issued \(WC24Time.date(h.issued))  expires \(WC24Time.date(h.expires))  country \(h.countryCode) lang \(h.language) region \(h.regionFlag)")
    if let m = f.message { print("MESSAGE: \(m)") }
    print("long \(f.longForecasts.count)  summary \(f.summaries.count)  weather types \(f.weatherTypes.count)  uv \(f.uvIndex.count)  places \(f.places.count)")
    let want = opt("--city")?.lowercased()
    let cities = want.map { w in f.places.filter { $0.city.lowercased() == w } } ?? Array(f.places.prefix(3))
    for p in cities {
        print("\n[\(p.id)] \(p.city), \(p.region ?? "-"), \(p.country ?? "-")  lat \(p.latitudeDegrees) lon \(p.longitudeDegrees) rank \(p.zoom1)/\(p.zoom2)")
        if let l = f.longForecasts.first(where: { $0.location == p.id }) {
            print("  utc offset \(l.time.utcOffsetMinutes) min")
            print("  today:    " + dayLine(l.today, f)); print("  tomorrow: " + dayLine(l.tomorrow, f))
            for (i, w) in l.week.enumerated() { print("  +\(i + 2)d: \(f.weatherName(for: w.weather) ?? "?") \(w.highF)/\(w.lowF)°F \(w.precipitation)%") }
        } else if let s = f.summaries.first(where: { $0.location == p.id }) {
            print("  utc offset \(s.time.utcOffsetMinutes) min")
            print("  today:    " + dayLine(s.today, f)); print("  tomorrow: " + dayLine(s.tomorrow, f))
        }
        if let sb, let sf = try? ShortFile(sb), let c = sf.current.first(where: { $0.location == p.id }) {
            print("  now: \(f.weatherName(for: c.weather) ?? "?") \(c.tempF)°F/\(c.tempC)°C wind \(c.windDirection) \(c.windMph)mph")
        }
    }
}

// MARK: iOS Settings bundle

/// The iPhone app's native Settings page: the channel's three settings (CSetting) — closest location, temperature
/// display, wind display. Location values are the channel's location IDs (deterministic from the city catalog).
func writeSettingsBundle(_ path: String) throws {
    let gen = ForecastGenerator()
    let ids = gen.locationIDs()
    var rows: [(title: String, id: UInt32)] = []
    for (c, id) in zip(gen.cities, ids) where c.isHome {
        rows.append(("\(c.name), \(c.region ?? "")", id.raw))
    }
    rows.sort { $0.title.localizedStandardCompare($1.title) == .orderedAscending }
    let location: [String: Any] = [
        "Type": "PSMultiValueSpecifier", "Title": "Closest Location", "Key": "location",
        "DefaultValue": 0, "Titles": ["Current Location"] + rows.map(\.title), "Values": [0] + rows.map { Int($0.id) },
    ]
    let temp: [String: Any] = [
        "Type": "PSMultiValueSpecifier", "Title": "Temperature Display", "Key": "temp_unit",
        "DefaultValue": 1, "Titles": ["Celsius", "Fahrenheit"], "Values": [0, 1],
    ]
    let wind: [String: Any] = [
        "Type": "PSMultiValueSpecifier", "Title": "Wind Display", "Key": "wind_unit",
        "DefaultValue": 0, "Titles": ["mph", "km/h"], "Values": [0, 1],
    ]
    // Apple-style: just the units (location is automatic — iOS adds its own Location permission row).
    _ = location
    let root: [String: Any] = [
        "StringsTable": "Root",
        "PreferenceSpecifiers": [
            ["Type": "PSGroupSpecifier", "Title": "Units"],
            ["Type": "PSMultiValueSpecifier", "Title": "Temperature", "Key": "temp_unit",
             "DefaultValue": 1, "Titles": ["Celsius", "Fahrenheit"], "Values": [0, 1]],
            ["Type": "PSMultiValueSpecifier", "Title": "Wind Speed", "Key": "wind_unit",
             "DefaultValue": 0, "Titles": ["mph", "km/h"], "Values": [0, 1]],
        ],
    ]
    _ = temp; _ = wind
    let data = try PropertyListSerialization.data(fromPropertyList: root, format: .xml, options: 0)
    let url = URL(fileURLWithPath: path)
    try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
    try data.write(to: url)
    print("wrote \(url.path)")
}

// MARK: main

let sema = DispatchSemaphore(value: 0)
var exitCode: Int32 = 0
Task {
    do {
        switch args.first {
        case "cities": try buildCities()
        case "ranks":   // globe marker rank distribution of the catalog (zoom1 → count)
            var hist: [UInt8: Int] = [:]
            for c in ForecastGenerator().cities { hist[ForecastGenerator.rank(c).0, default: 0] += 1 }
            print(hist.sorted { $0.key < $1.key }.map { "\($0.key): \($0.value)" }.joined(separator: "  "))
        case "generate":
            let out = URL(fileURLWithPath: opt("--out") ?? "fcdata-out")
            try FileManager.default.createDirectory(at: out, withIntermediateDirectories: true)
            let gen = ForecastGenerator()
            print("fetching \(gen.cities.count) locations from Open-Meteo…")
            let t0 = Date()
            let o = try await gen.fetchAndBuild { done, total in print("  \(done)/\(total)") }
            try Data(o.forecast).write(to: out.appendingPathComponent("forecast.bin"))
            try Data(o.short).write(to: out.appendingPathComponent("short.bin"))
            try Data(o.forecastContainer).write(to: out.appendingPathComponent("forecast.wc24"))
            try Data(o.shortContainer).write(to: out.appendingPathComponent("short.wc24"))
            print(String(format: "done in %.1fs: forecast.bin %d B (container %d B), short.bin %d B", Date().timeIntervalSince(t0),
                         o.forecast.count, o.forecastContainer.count, o.short.count))
        case "settings-bundle":   // iOS Settings.bundle/Root.plist: closest location (home-country cities), units
            guard args.count >= 2 else { fail("usage: fcdata settings-bundle <Root.plist>") }
            try writeSettingsBundle(args[1])
        case "dump":
            guard args.count >= 2 else { fail("usage: fcdata dump <forecast> [short] [--city name]") }
            let short = args.count >= 3 && !args[2].hasPrefix("--") ? args[2] : nil
            try dump(args[1], short)
        default:
            print("usage: fcdata cities | generate --out dir | dump <forecast> [short] [--city name]")
        }
    } catch { print("error: \(error)"); exitCode = 1 }
    sema.signal()
}
sema.wait()
exit(exitCode)
