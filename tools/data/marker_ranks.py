#!/usr/bin/env python3 -I
"""Globe marker ranks (Place zoom1/zoom2) from RiiConnect24 File-Maker's forecastlists.py
(https://github.com/RiiConnect24/File-Maker, Channels/Forecast_Channel/forecastlists.py), which carries the
per-city zoom levels of the original Forecast Channel data. Usage: marker_ranks.py forecastlists.py > MarkerRanks.swift
Keys: "city|state" for the US list (weathercities049), "city|country" for weathercities_international."""
import sys, unicodedata
def norm(s): return unicodedata.normalize('NFKD', s).encode('ascii', 'ignore').decode().lower().strip()
ns = {}
exec(open(sys.argv[1], encoding='utf-8').read(), ns)
out = {}
for listname, use_region in (('weathercities049', True), ('weathercities_international', False)):
    for key, v in ns[listname].items():
        city = v[0][1]; region = v[1][1] if use_region else None; country = v[2][1]
        hexs = v[3]; z1 = int(hexs[8:10], 16); z2 = int(hexs[10:12], 16)
        k = norm(city) + '|' + norm(region if use_region else country)
        out.setdefault(k, (z1, z2))
print('// GENERATED by tools/data/marker_ranks.py — do not edit.')
print('// Globe marker ranks (zoom1, zoom2) of the original Forecast Channel city lists, as preserved in')
print('// RiiConnect24 File-Maker (https://github.com/RiiConnect24/File-Maker, forecastlists.py).')
print('// Keys: "city|us state" (US list) and "city|country" (international list), ASCII-folded, lowercase.')
print('enum MarkerRanks {')
print('    static let table: [String: (UInt8, UInt8)] = [')
for k in sorted(out):
    z1, z2 = out[k]
    print(f'        "{k}": ({z1}, {z2}),')
print('    ]')
print('}')
